#!/usr/bin/env node
// Assembles importable n8n workflow JSON from n8n/src (JS logic + SQL), so the code that runs in
// n8n is exactly the code the unit tests cover. Output: n8n/workflows/*.json
//
//   node scripts/build-workflows.mjs          # write files
//   node scripts/build-workflows.mjs --check  # fail if committed JSON is out of date (CI)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = (p) => readFileSync(join(root, 'n8n/src', p), 'utf8');

// SQL: strip full-line comments (pg-promise substitutes $n even inside comments).
const sql = (name) => src(`sql/${name}.sql`).split('\n').filter((l) => !l.trim().startsWith('--')).join('\n').trim();

// Each Code node gets the library of its module inlined as LIB.
const libs = {
  a1: ['discovery-lib.js', 'DiscoveryLib'],
  c1: ['email-lib.js', 'EmailLib'],
};
const libSource = (file) => src(file).replace(/^if \(typeof module.*$/m, '');
const code = (name) => {
  const header = `// Generated by scripts/build-workflows.mjs from n8n/src. Edit the source files, not this node.\n`;
  const lib = libs[name.slice(0, 2)];
  return lib
    ? `${header}const LIB = (() => {\n${libSource(lib[0])}\nreturn ${lib[1]};\n})();\n\n${src(`nodes/${name}.js`)}`
    : `${header}${src(`nodes/${name}.js`)}`;
};

const PG = { postgres: { id: 'careerPostgres01', name: 'Career Postgres' } };
const ANTHROPIC = { httpHeaderAuth: { id: 'anthropicApiKey1', name: 'Anthropic API key' } };
const GMAIL = { gmailOAuth2: { id: 'gmailOAuthCareer', name: 'Gmail (career agent)' } };
const TELEGRAM = { telegramApi: { id: 'telegramBotApi01', name: 'Telegram bot' } };

// Gmail REST call through the Gmail OAuth2 credential (scopes: gmail.readonly + gmail.compose).
function gmailHttp(id, name, position, { method = 'GET', url, body, batch = true }) {
  const parameters = { method, url, authentication: 'predefinedCredentialType', nodeCredentialType: 'gmailOAuth2', options: { timeout: 30000 } };
  if (body) Object.assign(parameters, { sendBody: true, specifyBody: 'json', jsonBody: body });
  if (batch) parameters.options.batching = { batch: { batchSize: 5, batchInterval: 300 } };
  return { id, name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position, parameters, credentials: GMAIL };
}
const claudeHttp = (id, name, position) => ({
  id, name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position,
  parameters: {
    method: 'POST', url: '={{ $json.url }}',
    authentication: 'genericCredentialType', genericAuthType: 'httpHeaderAuth',
    sendHeaders: true, specifyHeaders: 'json', jsonHeaders: '={{ $json.headers_json }}',
    sendBody: true, specifyBody: 'json', jsonBody: '={{ $json.body_json }}',
    options: { timeout: 180000 },
  },
  credentials: ANTHROPIC, retryOnFail: true, maxTries: 3, waitBetweenTries: 5000, onError: 'continueRegularOutput',
});

function pgNode(id, name, position, query, replacement, extra = {}) {
  const options = replacement ? { queryReplacement: replacement } : {};
  return {
    id, name, type: 'n8n-nodes-base.postgres', typeVersion: 2.8, position,
    parameters: { operation: 'executeQuery', query: `=${query}`, options },
    credentials: PG, retryOnFail: true, maxTries: 3, waitBetweenTries: 3000, ...extra,
  };
}
function codeNode(id, name, position, file) {
  return { id, name, type: 'n8n-nodes-base.code', typeVersion: 2, position, parameters: { mode: 'runOnceForAllItems', jsCode: code(file) } };
}
const link = (...names) => ({ main: [names.map((node) => ({ node, type: 'main', index: 0 }))] });

