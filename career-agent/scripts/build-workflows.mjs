#!/usr/bin/env node
// Assembles importable n8n workflow JSON from n8n/src (JS logic + SQL), so the code that runs in
// n8n is exactly the code the unit tests cover. Output: n8n/workflows/*.json
//
//   node scripts/build-workflows.mjs          # write files
//   node scripts/build-workflows.mjs --check  # fail if committed JSON is out of date (CI)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = (p) => readFileSync(join(root, 'n8n/src', p), 'utf8');

// SQL: strip full-line comments (pg-promise substitutes $n even inside comments).
const sql = (name) => src(`sql/${name}.sql`).split('\n').filter((l) => !l.trim().startsWith('--')).join('\n').trim();

const lib = src('discovery-lib.js').replace(/^if \(typeof module.*$/m, '');
const code = (name) =>
  `// Generated by scripts/build-workflows.mjs from n8n/src. Edit the source files, not this node.\n` +
  `const LIB = (() => {\n${lib}\nreturn DiscoveryLib;\n})();\n\n${src(`nodes/${name}.js`)}`;

const PG = { postgres: { id: 'careerPostgres01', name: 'Career Postgres' } };
const ANTHROPIC = { httpHeaderAuth: { id: 'anthropicApiKey1', name: 'Anthropic API key' } };

function pgNode(id, name, position, query, replacement, extra = {}) {
  const options = replacement ? { queryReplacement: replacement } : {};
  return {
    id, name, type: 'n8n-nodes-base.postgres', typeVersion: 2.8, position,
    parameters: { operation: 'executeQuery', query: `=${query}`, options },
    credentials: PG, retryOnFail: true, maxTries: 3, waitBetweenTries: 3000, ...extra,
  };
}
function codeNode(id, name, position, file) {
  return { id, name, type: 'n8n-nodes-base.code', typeVersion: 2, position, parameters: { mode: 'runOnceForAllItems', jsCode: code(file) } };
}
const link = (...names) => ({ main: [names.map((node) => ({ node, type: 'main', index: 0 }))] });

// ---------------------------------------------------------------------------
// A1 Job Discovery
// ---------------------------------------------------------------------------
const a1 = {
  id: 'careerA1Discover',
  name: 'A1 Job Discovery',
  nodes: [
    {
      id: 'a1-schedule', name: 'Every day 07:00 IST', type: 'n8n-nodes-base.scheduleTrigger', typeVersion: 1.2, position: [0, 0],
      parameters: { rule: { interval: [{ field: 'cronExpression', expression: '0 7 * * *' }] } },
    },
    { id: 'a1-manual', name: 'Run manually', type: 'n8n-nodes-base.manualTrigger', typeVersion: 1, position: [0, 200], parameters: {} },
    pgNode('a1-start', 'Start run', [220, 100], sql('a1_start_run'), '={{ $execution.id }}'),
    pgNode('a1-config', 'Load config', [440, 100], sql('a1_load_config'), ''),
    codeNode('a1-build', 'Build requests', [660, 100], 'a1_build_requests'),
    {
      id: 'a1-fetch', name: 'Fetch job board', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position: [880, 100],
      parameters: {
        method: '={{ $json.method }}',
        url: '={{ $json.url }}',
        sendHeaders: true, specifyHeaders: 'json', jsonHeaders: '={{ $json.headers_json }}',
        sendBody: '={{ $json.send_body }}', specifyBody: 'json', jsonBody: '={{ $json.body_json }}',
        options: {
          timeout: 30000,
          batching: { batch: { batchSize: 1, batchInterval: 1500 } },
          response: { response: { fullResponse: true, neverError: true, responseFormat: 'json' } },
        },
      },
      // No retryOnFail: n8n retries a whole node, which would re-fetch every board. A failed board
      // is retried on the next daily run and counted in job_sources.consecutive_failures.
      onError: 'continueRegularOutput',
    },
    codeNode('a1-normalize', 'Normalize & filter', [1100, 100], 'a1_normalize'),
    pgNode('a1-save-jobs', 'Save jobs, expire, dedupe', [1320, 100], sql('a1_save_jobs'),
      '={{ $json.jobs_json }},{{ $json.run_id }},{{ $json.results_json }},{{ $json.max_failures }}'),
    pgNode('a1-select', 'Select jobs to score', [1540, 100], sql('a1_select_to_score'),
      "={{ $('Load config').first().json.cfg.prompt_version }},{{ $('Load config').first().json.cfg.max_jobs_scored_per_run }}",
      { alwaysOutputData: true }),
    {
      id: 'a1-if', name: 'Anything to score?', type: 'n8n-nodes-base.if', typeVersion: 2.2, position: [1760, 100],
      parameters: {
        conditions: {
          options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
          conditions: [{ id: 'has-id', leftValue: '={{ $json.id }}', rightValue: '', operator: { type: 'number', operation: 'exists', singleValue: true } }],
          combinator: 'and',
        },
        options: {},
      },
    },
    codeNode('a1-build-claude', 'Build Claude requests', [1980, 0], 'a1_build_claude'),
    {
      id: 'a1-loop', name: 'One job at a time', type: 'n8n-nodes-base.splitInBatches', typeVersion: 3, position: [2200, 0],
      parameters: { batchSize: 1, options: {} },
    },
    {
      id: 'a1-claude', name: 'Claude: score job', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position: [2420, -120],
      parameters: {
        method: 'POST',
        url: '={{ $json.url }}',
        authentication: 'genericCredentialType', genericAuthType: 'httpHeaderAuth',
        sendHeaders: true, specifyHeaders: 'json', jsonHeaders: '={{ $json.headers_json }}',
        sendBody: true, specifyBody: 'json', jsonBody: '={{ $json.body_json }}',
        options: { timeout: 180000 },
      },
      credentials: ANTHROPIC,
      retryOnFail: true, maxTries: 3, waitBetweenTries: 5000, onError: 'continueRegularOutput',
    },
    {
      id: 'a1-attach', name: 'Attach job', type: 'n8n-nodes-base.code', typeVersion: 2, position: [2640, -120],
      parameters: { mode: 'runOnceForAllItems', jsCode: "// Pair the Claude response (or error) with the job of this loop iteration.\nconst job = $('One job at a time').first().json.job;\nreturn $input.all().map((it) => ({ json: { job, response: it.json } }));" },
    },
    codeNode('a1-parse', 'Parse scores', [2640, 100], 'a1_parse_scores'),
    pgNode('a1-save-scores', 'Save scores', [2860, 100], sql('a1_save_scores'),
      '={{ $json.scores_json }},{{ $json.updates_json }},{{ $execution.id }},{{ $json.failures_json }}',
      { alwaysOutputData: true }),
    pgNode('a1-finish', 'Finish run', [3080, 100], sql('a1_finish_run'),
      "={{ $('Start run').first().json.run_id }},{{ $('Normalize & filter').first().json.results_json }},{{ $execution.id }}"),
  ],
  connections: {
    'Every day 07:00 IST': link('Start run'),
    'Run manually': link('Start run'),
    'Start run': link('Load config'),
    'Load config': link('Build requests'),
    'Build requests': link('Fetch job board'),
    'Fetch job board': link('Normalize & filter'),
    'Normalize & filter': link('Save jobs, expire, dedupe'),
    'Save jobs, expire, dedupe': link('Select jobs to score'),
    'Select jobs to score': link('Anything to score?'),
    'Anything to score?': { main: [[{ node: 'Build Claude requests', type: 'main', index: 0 }], [{ node: 'Finish run', type: 'main', index: 0 }]] },
    'Build Claude requests': link('One job at a time'),
    // splitInBatches v3: output 0 = done (all collected results), output 1 = next item
    'One job at a time': { main: [[{ node: 'Parse scores', type: 'main', index: 0 }], [{ node: 'Claude: score job', type: 'main', index: 0 }]] },
    'Claude: score job': link('Attach job'),
    'Attach job': link('One job at a time'),
    'Parse scores': link('Save scores'),
    'Save scores': link('Finish run'),
  },
  settings: { executionOrder: 'v1', timezone: 'Asia/Kolkata', errorWorkflow: 'careerZ0ErrorHnd', saveManualExecutions: true, executionTimeout: 3600 },
  pinData: {},
  active: false,
};

// ---------------------------------------------------------------------------
// Z0 Error Handler (shared by every module's workflows)
// ---------------------------------------------------------------------------
const z0 = {
  id: 'careerZ0ErrorHnd',
  name: 'Z0 Error Handler',
  nodes: [
    { id: 'z0-trigger', name: 'On workflow error', type: 'n8n-nodes-base.errorTrigger', typeVersion: 1, position: [0, 0], parameters: {} },
    pgNode('z0-log', 'Log error', [240, 0], sql('z0_log_error'),
      '={{ $json.workflow.name }},{{ $json.execution.id }},{{ $json.execution.lastNodeExecuted }},{{ ($json.execution.error && $json.execution.error.message) || "unknown error" }},{{ JSON.stringify($json.execution) }}'),
    {
      id: 'z0-telegram', name: 'Telegram alert (optional)', type: 'n8n-nodes-base.telegram', typeVersion: 1.2, position: [480, 0], disabled: true,
      parameters: {
        chatId: "={{ $('Log error').first().json.telegram_chat_id }}",
        text: "=⚠️ Career agent: {{ $('On workflow error').first().json.workflow.name }} failed at \"{{ $('On workflow error').first().json.execution.lastNodeExecuted }}\"\n{{ $('On workflow error').first().json.execution.error.message }}\n{{ $('On workflow error').first().json.execution.url }}",
        additionalFields: { appendAttribution: false },
      },
      credentials: { telegramApi: { id: 'telegramBotApi01', name: 'Telegram bot' } },
    },
  ],
  connections: { 'On workflow error': link('Log error'), 'Log error': link('Telegram alert (optional)') },
  settings: { executionOrder: 'v1', timezone: 'Asia/Kolkata' },
  pinData: {},
  active: false,
};

const outDir = join(root, 'n8n/workflows');
mkdirSync(outDir, { recursive: true });
const files = { 'A1_job_discovery.json': a1, 'Z0_error_handler.json': z0 };
let stale = false;
for (const [file, wf] of Object.entries(files)) {
  const json = JSON.stringify(wf, null, 2) + '\n';
  const path = join(outDir, file);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch {}
    if (current !== json) { console.error(`${file} is out of date: run node scripts/build-workflows.mjs`); stale = true; }
  } else {
    writeFileSync(path, json);
    console.log(`wrote n8n/workflows/${file}`);
  }
}
process.exit(stale ? 1 : 0);
